import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// Regenerate one upstream fragment without replacing the app's reviewed choreography.
const prototypeRoot = process.argv[2];
const baseline = process.argv[3];
assert(prototypeRoot && /^[0-9a-f]{40}$/.test(baseline || ''), 'Usage: node sync-marine-water.mjs PROTOTYPE_ROOT BASELINE_SHA');
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const relative = 'prototypes/multimodal-marine-native/marine-water.js';
const normalize = (source) => source.replace(/\r\n/g, '\n').trim();
const original = normalize(execFileSync('git', ['-C', prototypeRoot, 'show', `${baseline}:${relative}`], { encoding: 'utf8' }));
const current = normalize(await readFile(path.join(prototypeRoot, relative), 'utf8'));
const sourceHead = execFileSync('git', ['-C', prototypeRoot, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
const sourceDirty = execFileSync('git', ['-C', prototypeRoot, 'status', '--porcelain', '--', relative], { encoding: 'utf8' }).trim() !== '';
const target = path.join(root, 'frontend/src/app/landing/multimodal/jsl-multimodal.mjs');
const host = (await readFile(target, 'utf8')).replace(/\r\n/g, '\n');
const originalCount = host.split(original).length - 1;
const currentCount = host.split(current).length - 1;
assert(originalCount === 1 || currentCount === 1, 'Expected one complete source fragment; refusing a partial patch');
let next = originalCount === 1 ? host.replace(original, current) : host;
const withoutWater = (source, fragment) => source.replace(/^\/\/ Marine water source:.*\n/m, '').replace(fragment, '/* WATER FRAGMENT */');
assert.equal(withoutWater(host, originalCount === 1 ? original : current), withoutWater(next, current), 'Unrelated app code changed');
const hash = createHash('sha256').update(current).digest('hex');
const provenance = `// Marine water source: ${sourceHead}${sourceDirty ? ' working tree' : ''}, sha256 ${hash}; regenerated by sync-marine-water.mjs.\n`;
next = next.replace(/^\/\/ Marine water source:.*\n/m, '');
const firstLine = next.indexOf('\n') + 1;
next = next.slice(0, firstLine) + provenance + next.slice(firstLine);
await writeFile(target, next);
console.log(JSON.stringify({ baseline, sourceHead, sourceDirty, sourceSha256: hash, unrelatedAppCodePreserved: true }));
