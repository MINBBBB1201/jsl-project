const { chromium } = require('playwright');
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { spawn } = require('node:child_process');
const project = path.resolve(__dirname,'../..');
const artifacts = path.join(__dirname,'artifacts');
const media = path.join(artifacts,'industrial-prototype');
const files = ['frontend/src/app/landing/landing-page-content.tsx',...['industrial-journey.tsx','industrial-scenes.tsx','industrial-motion.ts','industrial-journey.css'].map(x=>'frontend/src/app/landing/components/'+x),...['port.webp','warehouse.webp','truck.webp'].map(x=>'frontend/public/images/landing/industrial/'+x)];
const hashes = Object.fromEntries(files.map(x=>[x,crypto.createHash('sha256').update(fs.readFileSync(path.join(project,x))).digest('hex')]));
const snapshotId = crypto.createHash('sha256').update(JSON.stringify(hashes)).digest('hex');
fs.writeFileSync(path.join(artifacts,'industrial-snapshot.json'),JSON.stringify({snapshotId,createdAt:new Date().toISOString(),files:hashes},null,2));
let ownedBrowser;
(async()=>{
 const browser = ownedBrowser = await chromium.launch({channel:'chrome',headless:true});
 const context = await browser.newContext({viewport:{width:1440,height:900}});
 const page = await context.newPage();
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://localhost:3000/landing',{waitUntil:'domcontentloaded',timeout:60000});
 await page.waitForFunction(()=>document.querySelector('.industrial-journey')?.dataset.progress!==undefined);
 const start = await page.locator('.industrial-journey').evaluate(e=>e.getBoundingClientRect().top+scrollY);
 await page.evaluate(y=>scrollTo({top:y+innerHeight*10*.59,behavior:'instant'}),start);
 await page.waitForTimeout(700);
 await page.locator('.industrial-step-nav button').nth(3).click();await page.waitForTimeout(1600);
 const stageButton=await page.locator('.industrial-step-label').innerText();
 if(!stageButton.includes('PREPARATION'))throw new Error('Stage button did not reach preparation');
 await page.locator('.industrial-skip').click();await page.waitForTimeout(1500);
 const skipped=await page.locator('.industrial-stage').evaluate(e=>e.getBoundingClientRect().bottom<1);
 if(!skipped)throw new Error('Skip did not leave pinned stage');
 await page.emulateMedia({reducedMotion:'reduce'});await page.waitForTimeout(600);
 await page.emulateMedia({reducedMotion:'no-preference'});await page.waitForTimeout(600);
 const resetStart=await page.locator('.industrial-journey').evaluate(e=>e.getBoundingClientRect().top+scrollY);
 await page.evaluate(y=>scrollTo({top:y,behavior:'instant'}),resetStart);await page.waitForTimeout(700);
 const resetTitle=await page.locator('#industrial-service-title').innerText();
 if(resetTitle!=='A full line-up of five transport modes')throw new Error('Reduced-motion toggle did not restore overview title');
 await context.close();
 const filmContext=await browser.newContext({viewport:{width:1440,height:900},recordVideo:{dir:media,size:{width:1440,height:900}}});
 const film=await filmContext.newPage();await film.goto('http://localhost:3000/landing',{waitUntil:'domcontentloaded',timeout:60000});
 await film.waitForFunction(()=>document.querySelector('.industrial-journey')?.dataset.progress!==undefined);
 await film.evaluate(async()=>{await document.fonts.ready;await document.querySelector('.industrial-vehicle img').decode()});
 const y=await film.locator('.industrial-journey').evaluate(e=>e.getBoundingClientRect().top+scrollY);
 await film.evaluate(y=>scrollTo({top:y+135,behavior:'instant'}),y);await film.waitForTimeout(800);
 console.log('Recording real landing scroll');
 await film.evaluate(async y=>{const start=performance.now();await new Promise(resolve=>{const draw=()=>{const t=Math.min(1,(performance.now()-start)/18000);scrollTo({top:y+t*innerHeight*10,behavior:'instant'});if(t<1)requestAnimationFrame(draw);else resolve()};requestAnimationFrame(draw)})},y);
 await film.waitForTimeout(700);
 const video=film.video();await film.close();await filmContext.close();
 const videoPath=path.join(media,'live-scroll-18s.webm');await video.saveAs(videoPath);
 await browser.close();
 const report={snapshotId,stageButton,skipped,resetTitle,pageErrors:errors,video:videoPath};
 fs.writeFileSync(path.join(artifacts,'industrial-interaction.json'),JSON.stringify(report,null,2));
 console.log(JSON.stringify(report));
 const ffmpeg=require('ffmpeg-static');
 const child=spawn(ffmpeg,['-hide_banner','-loglevel','error','-n','-i',videoPath,'-c:v','libx264','-preset','veryfast','-crf','23','-pix_fmt','yuv420p','-movflags','+faststart',path.join(media,'live-scroll.mp4')],{windowsHide:true,stdio:'inherit'});
 await new Promise((resolve,reject)=>{child.on('error',reject);child.on('close',code=>code===0?resolve():reject(new Error('ffmpeg '+code)))});
})().catch(async error=>{console.error(error);await ownedBrowser?.close().catch(()=>{});process.exitCode=1});
