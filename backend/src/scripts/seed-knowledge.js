const seed = async () => {
  await connectDB();

  const reset = process.argv.includes('--reset');
  if (reset) {
    const { deletedCount } = await KnowledgeDoc.deleteMany({});
    logger.info(`--reset: 기존 지식 문서 ${deletedCount}건 삭제`);
  }

  const existing = await KnowledgeDoc.countDocuments();
  if (existing > 0 && !reset) {
    logger.warn(`지식 문서가 이미 ${existing}건 있습니다. 다시 넣으려면 --reset 옵션을 사용하세요.`);
  } else {
    // isSample 은 문서마다 적지 않고 여기서 묶어서 붙인다. 배열이 곧 분류라
    // 새 문서를 엉뚱한 배열에 넣지 않는 한 플래그가 어긋날 수 없다.
    const inserted = await KnowledgeDoc.insertMany([
      ...SAMPLE_DOCS.map(d => ({ ...d, isSample: true })),
      ...OPERATIONAL_DOCS.map(d => ({ ...d, isSample: false }))
    ]);
    logger.info(
      `지식 문서 ${inserted.length}건 삽입 완료 ` +
      `(플레이스홀더 ${SAMPLE_DOCS.length} / 실제 절차 ${OPERATIONAL_DOCS.length})`
    );
  }

  // text index가 실제로 생성됐는지 확인
  await KnowledgeDoc.syncIndexes();
  const indexes = await KnowledgeDoc.collection.indexes();
  const textIndex = indexes.find(i => Object.values(i.key).includes('text'));
  logger.info(`text index: ${textIndex ? textIndex.name : '없음(!)'}`);

  const docs = await KnowledgeDoc.find({}, 'title category isSample').sort({ category: 1 });
  docs.forEach(d =>
    logger.info(`  - [${d.category}] ${d.title}${d.isSample ? '  (샘플 — 검색 제외)' : ''}`)
  );

  const searchable = docs.filter(d => !d.isSample).length;
  logger.info(`검색 대상 문서: ${searchable}건 / 전체 ${docs.length}건`);

  await closeDB();
};

seed().catch(async (err) => {
  logger.error('시드 실패:', err);
  await mongoose.connection.close().catch(() => {});
  process.exit(1);
});
